"""Build guide/python.json for the Python Preparation page.

Source: guide/python/*.md, read in file-name order.
  "## Title"    starts a chapter
  "### Title"   starts a question; everything until the next heading is its answer

Chapters and questions are numbered here, so the Markdown stays unnumbered and
questions can be added or moved freely.

Usage:  pip install markdown && python tools/build_python_guide.py
"""
import html
import json
import pathlib
import re

import markdown

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "guide" / "python"
OUT = ROOT / "guide" / "python.json"

MD_EXT = ["fenced_code", "tables"]


def render(text):
    return markdown.markdown(text, extensions=MD_EXT)


def render_inline(text):
    out = render(text).strip()
    return re.sub(r"^<p>(.*)</p>$", r"\1", out, flags=re.S)


def plain(html_text):
    return re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", " ", html_text))).strip()


def slug(text):
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def main():
    lines = "\n\n".join(p.read_text(encoding="utf-8") for p in sorted(SRC.glob("*.md"))).splitlines()
    chapters, chapter, question = [], None, None

    def close_question():
        nonlocal question
        if question is not None:
            body = "\n".join(question.pop("_lines")).strip()
            question["html"] = render(body)
            question["text"] = plain(question["html"])
            chapter["questions"].append(question)
            question = None

    for line in lines:
        if line.startswith("## "):
            close_question()
            if chapter is not None and chapter["_intro"]:
                chapter["intro"] = render_inline(" ".join(chapter["_intro"]).strip())
            title = line[3:].strip()
            chapter = {"id": slug(title), "title": title, "intro": "", "_intro": [], "questions": []}
            chapters.append(chapter)
        elif line.startswith("### "):
            close_question()
            raw = line[4:].strip()
            question = {"title": plain(render_inline(raw)), "titleHtml": render_inline(raw), "_lines": []}
        elif question is not None:
            question["_lines"].append(line)
        elif chapter is not None and line.strip():
            chapter["_intro"].append(line.strip())
    close_question()

    n = 0
    for c in chapters:
        if c["_intro"] and not c["intro"]:
            c["intro"] = render_inline(" ".join(c["_intro"]))
        del c["_intro"]
        for q in c["questions"]:
            n += 1
            q["n"] = n

    data = {
        "_note": "Generated by tools/build_python_guide.py from guide/python/*.md. Edit the Markdown, then rebuild.",
        "title": "Python Preparation",
        "chapters": chapters,
    }
    OUT.write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"{len(chapters)} chapters, {n} questions -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
